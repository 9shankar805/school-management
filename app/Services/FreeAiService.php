<?php

namespace App\Services;

use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;
use Exception;

class FreeAiService
{
    /**
     * Generate text using Groq API with automatic model failovers and backup providers.
     *
     * @param string $prompt
     * @return string
     * @throws Exception
     */
    public function generate(string $prompt): string
    {
        $apiKey = config('services.groq.key') ?: env('GROQ_API_KEY', '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');
        
        $configuredModel = config('services.groq.model');

        // Build candidate list: configured model first, then fallbacks.
        // Exclude removed/deprecated models that no longer exist on Groq.
        $deprecated = ['llama-3.3-70b-versatile', 'llama3-70b-8192', 'mixtral-8x7b-32768'];

        // Prefer non-reasoning models first for structured JSON tasks (groq/compound has
        // no TPM reasoning overhead). Reasoning models (gpt-oss, qwen) are fallbacks.
        $fallbacks = [
            'groq/compound',        // fast, non-reasoning, generous limits — best for JSON
            'groq/compound-mini',   // smaller but still non-reasoning
            'openai/gpt-oss-20b',   // reasoning model, lower cost
            'openai/gpt-oss-120b',  // reasoning model, high quality
            'qwen/qwen3.6-27b',     // last resort — very tight TPM limit
        ];

        $candidateModels = array_unique(array_filter(
            array_merge([$configuredModel], $fallbacks),
            fn($m) => !empty($m) && !in_array($m, $deprecated)
        ));

        if ($apiKey) {
            foreach ($candidateModels as $model) {
                try {
                    $payload = [
                        'model'       => $model,
                        'messages'    => [
                            ['role' => 'user', 'content' => $prompt]
                        ],
                        'temperature' => 0.2,
                        'max_completion_tokens' => 4096,
                    ];

                    // Reasoning models (Qwen, DeepSeek, gpt-oss) consume part of
                    // max_completion_tokens for internal thinking even when
                    // reasoning_format is hidden. Increase the budget so there are
                    // enough tokens left for actual JSON output after thinking.
                    $isReasoningModel = str_contains(strtolower($model), 'qwen')
                        || str_contains(strtolower($model), 'deepseek')
                        || str_contains(strtolower($model), 'gpt-oss');
                    if ($isReasoningModel) {
                        $payload['reasoning_format'] = 'hidden';
                        $payload['max_completion_tokens'] = 8192; // reasoning tokens + output tokens
                    }

                    $response = Http::withToken($apiKey)
                        ->timeout(45)
                        ->post('https://api.groq.com/openai/v1/chat/completions', $payload);

                    if ($response->successful()) {
                        $content = $response->json('choices.0.message.content');
                        if (!empty($content)) {
                            // Strip reasoning <think>...</think> tags if generated by models like Qwen/DeepSeek
                            $content = preg_replace('/<think>.*?<\/think>/s', '', $content);
                            return trim($content);
                        }
                    }

                    Log::warning("Groq AI generation warning for model {$model}", [
                        'status'   => $response->status(),
                        'response' => $response->json(),
                    ]);
                } catch (\Throwable $e) {
                    Log::error("Groq AI exception for model {$model}: " . $e->getMessage());
                }
            }
        }

        // Fallback 1: Pollinations AI (GET)
        try {
            $url = 'https://text.pollinations.ai/' . urlencode($prompt);
            $response = Http::timeout(25)->get($url);

            if ($response->successful()) {
                $body = $response->body();
                if (!empty($body)) {
                    return trim($body);
                }
            }
        } catch (\Throwable $e) {
            Log::error('Pollinations AI fallback failed: ' . $e->getMessage());
        }

        // Fallback 2: Pollinations AI (POST JSON)
        try {
            $response = Http::timeout(25)->post('https://text.pollinations.ai/openai', [
                'messages' => [
                    ['role' => 'user', 'content' => $prompt]
                ]
            ]);

            if ($response->successful()) {
                $content = $response->json('choices.0.message.content') ?: $response->body();
                if (!empty($content)) {
                    return trim($content);
                }
            }
        } catch (\Throwable $e) {
            Log::error('Pollinations AI POST fallback failed: ' . $e->getMessage());
        }

        throw new Exception("AI Generation failed across all providers. Please check network connectivity or API key.");
    }

    /**
     * Generate text from image + prompt using active Groq Vision API.
     *
     * @param string $prompt
     * @param string $imageBase64
     * @param string $mimeType
     * @return string
     * @throws Exception
     */
    public function generateVision(string $prompt, string $imageBase64, string $mimeType = 'image/jpeg'): string
    {
        $apiKey = config('services.groq.key') ?: env('GROQ_API_KEY', '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');
        
        $visionModels = [
            'openai/gpt-oss-120b',
            'openai/gpt-oss-20b',
            'qwen/qwen3.6-27b',
        ];

        $dataUrl = "data:{$mimeType};base64,{$imageBase64}";

        if ($apiKey) {
            foreach ($visionModels as $model) {
                try {
                    $payload = [
                        'model'    => $model,
                        'messages' => [
                            [
                                'role' => 'user',
                                'content' => [
                                    ['type' => 'text', 'text' => $prompt],
                                    ['type' => 'image_url', 'image_url' => ['url' => $dataUrl]],
                                ]
                            ]
                        ],
                        'temperature' => 0.2,
                        'max_completion_tokens' => 4096,
                    ];

                    $isReasoningModel = str_contains(strtolower($model), 'qwen')
                        || str_contains(strtolower($model), 'deepseek')
                        || str_contains(strtolower($model), 'gpt-oss');
                    if ($isReasoningModel) {
                        $payload['reasoning_format'] = 'hidden';
                        $payload['max_completion_tokens'] = 8192;
                    }

                    $response = Http::withToken($apiKey)
                        ->timeout(60)
                        ->post('https://api.groq.com/openai/v1/chat/completions', $payload);

                    if ($response->successful()) {
                        $content = $response->json('choices.0.message.content');
                        if (!empty($content)) {
                            // Strip reasoning <think>...</think> tags if present
                            $content = preg_replace('/<think>.*?<\/think>/s', '', $content);
                            return trim($content);
                        }
                    }

                    Log::warning("Groq Vision AI generation warning for model {$model}", [
                        'status'   => $response->status(),
                        'response' => $response->json(),
                    ]);
                } catch (\Throwable $e) {
                    Log::error("Groq Vision AI exception for model {$model}: " . $e->getMessage());
                }
            }
        }

        // Fallback: If vision model call fails, log and fallback to text model
        Log::warning('Groq Vision AI call failed across vision models, falling back to text generation.');
        return $this->generate($prompt);
    }
}
